// Generates supabase/seed.sql. Re-run with: node scripts/make-seed.mjs
import { writeFileSync } from 'node:fs'
import { roundRobin } from '../src/lib/fixtures.js'

const teams = [
  ['real-garibaldi', 'Real Garibaldi FC', 'RGF', '#0E1F45', '#D4A93C'],
  ['moscova-mafia', 'Moscova Mafia', 'MOS', '#036A38', '#111111'],
  ['sexy-sesto', 'Sexy Sesto FC', 'SSFC', '#E8323C', '#111111'],
  ['atletico-affori', 'Atletico Affori', 'ATA', '#FFCB05', '#0B1A40'],
  ['frattini-fratelli', 'Frattini Fratelli', 'FRF', '#1E6FD9', '#C9CED6'],
]
const sponsors = [
  ['Adlers Lombard', 'adlers-lombard', 'title'],
  ['Edusetin Study Abroad', 'edusetin', 'partner'],
  ['Flymart International Grocery Store', 'flymart', 'partner'],
  ['Saravanaa Bhavan Milan', 'saravanaa-bhavan', 'partner'],
  ['Kashmiria Fashion', 'kashmiria-fashion', 'partner'],
  ["God's Own Country Films", 'gods-own-country-films', 'partner'],
]
const q = s => s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`
// Sunday 22 Nov 2026, 10:00 Europe/Rome (UTC+1) = 09:00Z. One pitch: 10' match + 5' changeover.
const start = Date.parse('2026-11-22T09:00:00Z'), SLOT = 15 * 60_000
const at = i => q(new Date(start + i * SLOT).toISOString())

let sql = `-- MML 4.0 seed data. Run AFTER schema.sql. Generated by scripts/make-seed.mjs\n\n`
sql += `insert into teams (id, name, short_name, logo_url, primary_color, secondary_color, sort) values\n` +
  teams.map(([id, n, s, c1, c2], i) => `  (${q(id)}, ${q(n)}, ${q(s)}, ${q(`/logos/teams/${id}.webp`)}, ${q(c1)}, ${q(c2)}, ${i})`).join(',\n') +
  `\non conflict (id) do update set name = excluded.name, logo_url = excluded.logo_url, primary_color = excluded.primary_color, secondary_color = excluded.secondary_color;\n\n`
sql += `insert into sponsors (name, logo_url, tier, sort) select * from (values\n` +
  sponsors.map(([n, f, t], i) => `  (${q(n)}, ${q(`/logos/sponsors/${f}.webp`)}, ${q(t)}, ${i})`).join(',\n') +
  `\n) v(name, logo_url, tier, sort) where not exists (select 1 from sponsors);\n\n`
const rr = roundRobin(teams.map(t => t[0]))
const rows = rr.map(([h, a], i) => `  ('G${i + 1}', 'group', ${i + 1}, ${q(h)}, ${q(a)}, null, null, ${at(i)})`)
rows.push(`  ('SF1', 'sf', 1, null, null, 'G1', 'G4', ${at(10)})`)
rows.push(`  ('SF2', 'sf', 2, null, null, 'G2', 'G3', ${at(11)})`)
rows.push(`  ('F', 'final', 1, null, null, 'W:SF1', 'W:SF2', ${at(13)})`)
sql += `insert into matches (id, stage, number, home_team_id, away_team_id, home_source, away_source, kickoff_at) values\n${rows.join(',\n')}\non conflict (id) do nothing;\n\n`
sql += `insert into settings (key, value) values ('match_minutes', '10'), ('match_day', '"2026-11-22"')\non conflict (key) do nothing;\n`
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(sql)
