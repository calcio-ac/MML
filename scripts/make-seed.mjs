// Generates supabase/seed.sql from src/data/seedData.js. Re-run with: node scripts/make-seed.mjs
import { writeFileSync } from 'node:fs'
import { TEAMS, SPONSORS, buildMatches, SETTINGS } from '../src/data/seedData.js'

const q = s => s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`
let sql = `-- MML 4.0 seed data. Run AFTER schema.sql. Generated by scripts/make-seed.mjs\n\n`
sql += `insert into teams (id, name, short_name, logo_url, primary_color, secondary_color, sort) values\n` +
  TEAMS.map(t => `  (${[t.id, t.name, t.short_name, t.logo_url, t.primary_color, t.secondary_color].map(q).join(', ')}, ${t.sort})`).join(',\n') +
  `\non conflict (id) do update set name = excluded.name, logo_url = excluded.logo_url, primary_color = excluded.primary_color, secondary_color = excluded.secondary_color;\n\n`
sql += `insert into sponsors (name, logo_url, tier, sort) select * from (values\n` +
  SPONSORS.map(s => `  (${q(s.name)}, ${q(s.logo_url)}, ${q(s.tier)}, ${s.sort})`).join(',\n') +
  `\n) v(name, logo_url, tier, sort) where not exists (select 1 from sponsors);\n\n`
sql += `insert into matches (id, stage, number, home_team_id, away_team_id, home_source, away_source, kickoff_at) values\n` +
  buildMatches().map(m => `  (${q(m.id)}, ${q(m.stage)}, ${m.number}, ${[m.home_team_id, m.away_team_id, m.home_source, m.away_source, m.kickoff_at].map(q).join(', ')})`).join(',\n') +
  `\non conflict (id) do nothing;\n\n`
sql += `insert into settings (key, value) values\n` + Object.entries(SETTINGS).map(([k, v]) => `  (${q(k)}, ${q(JSON.stringify(v))})`).join(',\n') + `\non conflict (key) do nothing;\n`
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log('wrote supabase/seed.sql')
